% Make a separate copy so the original model remains available.
source = 'ann_transmission_line';
manual = 'ann_transmission_line_manual';

load_system(source);

if exist([manual '.slx'],'file')
    error('%s.slx already exists. Open that model instead.',manual);
end

save_system(source,manual);
load_system(manual);

% Show important parameter values below each block.
set_param([manual '/Source'],'AttributesFormatString', ...
    ['Voltage = %<Voltage> V' newline ...
     'Frequency = %<Frequency> Hz' newline ...
     'R = %<Resistance> ohm' newline ...
     'L = %<Inductance> H']);

set_param([manual '/Line1'],'AttributesFormatString', ...
    ['Length = %<Length> km' newline ...
     'R/km = %<Resistances>']);

set_param([manual '/Line2'],'AttributesFormatString', ...
    ['Length = %<Length> km' newline ...
     'R/km = %<Resistances>']);

set_param([manual '/Fault'],'AttributesFormatString', ...
    ['A = %<FaultA>, B = %<FaultB>, C = %<FaultC>' newline ...
     'Ground = %<GroundFault>' newline ...
     'Times = %<SwitchTimes> s' newline ...
     'Rf = %<FaultResistance> ohm' newline ...
     'Rg = %<GroundResistance> ohm']);

set_param([manual '/Transformer'],'AttributesFormatString', ...
    ['Rating = %<NominalPower>' newline ...
     'Primary = %<Winding1>' newline ...
     'Secondary = %<Winding2>']);

set_param([manual '/Load'],'AttributesFormatString', ...
    ['Nominal V = %<NominalVoltage> V' newline ...
     'P = %<ActivePower> W' newline ...
     'Q = %<InductivePower> var']);

set_param([manual '/powergui'],'AttributesFormatString', ...
    'Electrical sample time = %<SampleTime> s');

save_system(manual);
open_system(manual);